def share_links(url, title, root):
    u, t = urllib.parse.quote(url, safe=""), urllib.parse.quote(title, safe="")
    items = [("x", "X", f"https://x.com/intent/tweet?url={u}&text={t}"),
             ("facebook", "Facebook", f"https://www.facebook.com/sharer.php?u={u}"),
             ("at-symbol", "E-mail", f"mailto:?subject={t}&body={u}"),
             ("linkedin", "LinkedIn", f"https://www.linkedin.com/sharing/share-offsite/?url={u}"),
             ("whatsapp", "WhatsApp", f"https://wa.me/?text={t}%20{u}")]
    lis = "".join(f'<li><a href="{esc(h)}" target="_blank" rel="noopener" title="Share on {n}" aria-label="Share on {n}">{icon(i, root)}</a></li>'
                  for i, n, h in items)
    return f'<ul class="share"><li class="label">Share</li>{lis}</ul>'


