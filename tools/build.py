#!/usr/bin/env python3
"""
besimagargun.com page builder. Python 3 standard library only, nothing to install.

Run from anywhere:   python3 tools/build.py

It (re)creates the parts of the site that come from data files:
  * publications/index.html and publications/<slug>/   from data/publications.json (+ data/bib/<slug>.bib)
  * events/index.html and events/<slug>/                from data/talks.json
  * the "Selected Publications" and "Talks" blocks in index.html
  * the Experience / Education / Academic Service / Awards blocks of experience/index.html (copied from index.html)
  * sitemap.xml

Everything else (index.html, experience/index.html, 404.html, assets/) is plain HTML/CSS: edit it directly.
Blocks between <!-- BEGIN:name --> and <!-- END:name --> markers are rewritten by this script.
"""
