def share_links(url, title, root):
    u, t = urllib.parse.quote(url, safe=""), urllib.parse.quote(title, safe="")
    items = [("x", "Share on X", f"https://x.com/intent/tweet?url={u}&text={t}"),
             ("linkedin", "Share on LinkedIn", f"https://www.linkedin.com/sharing/share-offsite/?url={u}"),
             ("facebook", "Share on Facebook", f"https://www.facebook.com/sharer.php?u={u}"),
             ("whatsapp", "Share on WhatsApp", f"https://wa.me/?text={t}%20{u}"),
             ("at-symbol", "Share by e-mail", f"mailto:?subject={t}&body={u}")]
    new_tab = ' target="_blank" rel="noopener"'
    lis = "".join(f'<li><a href="{esc(h)}"{"" if h.startswith("mailto:") else new_tab}'
                  f' title="{n}" aria-label="{n}">{icon(i, root)}</a></li>' for i, n, h in items)
    return f'<ul class="share"><li class="label">Share</li>{lis}</ul>'


def author_card(root):
    return f"""<aside class="author-card">
    <picture><source srcset="{root}assets/img/me-192.webp" type="image/webp"><img src="{root}assets/img/me-192.jpg" width="64" height="64" alt="{OWNER}" loading="lazy"></picture>
    <div>
      <a class="name" href="{root}">{OWNER}</a>
      <p>{OWNER_ROLE}, {OWNER_PLACE}</p>
    </div>
  </aside>"""


def pager(items, i, kind, title_key="title"):
    newer = items[i - 1] if i > 0 else None
    older = items[i + 1] if i + 1 < len(items) else None
    left = (f'<a class="prev" href="../{newer["slug"]}/"><span class="dir">← Newer</span>'
            f'<span class="t">{esc(newer[title_key])}</span></a>') if newer else "<span></span>"
    right = (f'<a class="next" href="../{older["slug"]}/"><span class="dir">Older →</span>'
             f'<span class="t">{esc(older[title_key])}</span></a>') if older else "<span></span>"
    return f'<nav class="pager" aria-label="More {kind}">{left}{right}</nav>'


def topics(tags, skip=""):
    shown = [t for t in tags if t.lower() != skip.lower()]
    if not shown:
        return ""
    return f'<p class="keywords"><span>Topics</span>{", ".join(esc(t) for t in shown)}</p>'


def facts(rows):
    return '<dl class="facts">' + "".join(f"<dt>{k}</dt><dd>{v}</dd>" for k, v in rows) + "</dl>"


# ---------------------------------------------------------------- publications
def authors_html(authors, short=False):
    names = list(authors)
    shown = list(range(len(names)))
    etal = False
    if short and len(names) > 3:
        idx = next((i for i, a in enumerate(names) if is_owner(a)), None)
        shown = [0, 1, 2]
        if idx is not None and idx > 2:
            shown += [None, idx]
        etal = len(names) > max(i for i in shown if i is not None) + 1
    parts = []
    for i in shown:
        if i is None:
            parts.append("…")
        else:
            a = esc(names[i])
            parts.append(f'<span class="me">{a}</span>' if is_owner(names[i]) else a)
    if etal:
        parts.append("et al.")
    return ", ".join(parts)


def pub_links(p, pub_dir):
    links = []
    if p.get("pmid"):
        links.append(f'<a href="https://pubmed.ncbi.nlm.nih.gov/{esc(p["pmid"])}/" target="_blank" rel="noopener">PubMed</a>')
    links.append(f'<a href="{pub_dir}cite.bib" data-cite>Cite</a>')
    if p.get("doi"):
        links.append(f'<a href="https://doi.org/{esc(p["doi"])}" target="_blank" rel="noopener">DOI</a>')
    return '<p class="pub-links">' + "".join(links) + "</p>"


def pub_item(p, pub_dir, short=False, show_year=True):
    venue = f"<em>{esc(p['journal'])}</em>"
    if show_year:
        venue += f", {ymd(p['date'])[0]}"
    kind = p.get("type", "Journal article")
    if kind != "Journal article":
        venue += f" · {esc(kind)}"
    return (f'<li>\n'
            f'  <a class="pub-title" href="{pub_dir}">{esc(p["title"])}</a>\n'
            f'  <p class="pub-authors">{authors_html(p["authors"], short)}</p>\n'
            f'  <p class="pub-venue">{venue}</p>\n'
            f'  {pub_links(p, pub_dir)}\n'
            f'</li>')


def citation_extra(p, path):
    y, m, _ = ymd(p["date"])
    meta = [f'<meta name="citation_title" content="{esc(p["title"])}">']
    meta += [f'<meta name="citation_author" content="{esc(a)}">' for a in p["authors"]]
    meta.append(f'<meta name="citation_publication_date" content="{y}/{m:02d}">')
    meta.append(f'<meta name="citation_journal_title" content="{esc(p["journal"])}">')
    if p.get("volume"):
        meta.append(f'<meta name="citation_volume" content="{esc(p["volume"])}">')
    if p.get("issue"):
        meta.append(f'<meta name="citation_issue" content="{esc(p["issue"])}">')
    if p.get("pages"):
        first, _, last = p["pages"].partition("-")
        meta.append(f'<meta name="citation_firstpage" content="{esc(first)}">')
        if last:
            meta.append(f'<meta name="citation_lastpage" content="{esc(last)}">')
    if p.get("doi"):
        meta.append(f'<meta name="citation_doi" content="{esc(p["doi"])}">')
    if p.get("pmid"):
        meta.append(f'<meta name="citation_pmid" content="{esc(p["pmid"])}">')
    authors = [{"@type": "Person", "name": a, **({"@id": f"{SITE}/#person"} if is_owner(a) else {})}
               for a in p["authors"]]
    ld = {"@context": "https://schema.org", "@type": "ScholarlyArticle", "name": p["title"],
          "headline": clip(p["title"], 110), "author": authors, "datePublished": f"{y}-{m:02d}",
          "isPartOf": {"@type": "Periodical", "name": p["journal"]}, "url": f"{SITE}/{path}"}
    ids = []
    if p.get("doi"):
        ld["sameAs"] = f"https://doi.org/{p['doi']}"
        ids.append({"@type": "PropertyValue", "propertyID": "DOI", "value": p["doi"]})
    if p.get("pmid"):
        ids.append({"@type": "PropertyValue", "propertyID": "PMID", "value": p["pmid"]})
    if ids:
        ld["identifier"] = ids
    if p.get("abstract"):
        ld["abstract"] = " ".join(p["abstract"].split())
    return "\n".join(meta) + "\n" + jsonld(ld)


def make_bib(p):
    fields = [("author", " and ".join(p["authors"])), ("title", p["title"]), ("journal", p["journal"]),
              ("year", str(ymd(p["date"])[0])), ("volume", p.get("volume", "")), ("number", p.get("issue", "")),
              ("pages", p.get("pages", "").replace("-", "--")), ("doi", p.get("doi", "")), ("pmid", p.get("pmid", ""))]
    body = ",\n".join(f" {k} = {{{v}}}" for k, v in fields if v)
    return f"@article{{{p['slug'].replace('-', '')},\n{body}\n}}\n"


def year_groups(items, render):
    groups = []
    for x in items:
        y = ymd(x["date"])[0]
        if not groups or groups[-1][0] != y:
            groups.append((y, []))
        groups[-1][1].append(x)
    return "\n".join(f'<section class="year-group">\n<h2>{y}</h2>\n{render(xs)}\n</section>' for y, xs in groups)


def build_publications(pubs):
    changed = []
    for i, p in enumerate(pubs):
        path = f"publications/{p['slug']}/"
        root = "../../"
        kind = p.get("type", "Journal article")
        vol = p.get("volume", "")
        if vol:
            vol += f"({p['issue']})" if p.get("issue") else ""
            vol += f":{p['pages']}" if p.get("pages") else ""
        venue = [f"<em>{esc(p['journal'])}</em>", month_year(p["date"])] + ([esc(vol)] if vol else [])
        rows = [("Type", esc(kind)), ("Journal", f"<em>{esc(p['journal'])}</em>"), ("Published", month_year(p["date"]))]
        if vol:
            rows.append(("Volume", esc(vol)))
        if p.get("doi"):
            rows.append(("DOI", f'<a href="https://doi.org/{esc(p["doi"])}" target="_blank" rel="noopener">{esc(p["doi"])}</a>'))
        if p.get("pmid"):
            rows.append(("PMID", f'<a href="https://pubmed.ncbi.nlm.nih.gov/{esc(p["pmid"])}/" target="_blank" rel="noopener">{esc(p["pmid"])}</a>'))
        abstract = (f'<h2>Abstract</h2>\n  <div class="prose">\n{md(p["abstract"])}\n  </div>'
                    if p.get("abstract") else "")
        body = f"""<article>
  <header class="article-head">
    <p class="kicker"><a href="../">Publications</a> · {esc(kind)}</p>
    <h1>{esc(p['title'])}</h1>
    <p class="byline">{authors_html(p['authors'])}</p>
    <p class="venue">{' · '.join(venue)}</p>
    {pub_links(p, '')}
  </header>
  {abstract}
  <h2>Details</h2>
  {facts(rows)}
  {topics(p.get('tags', []), skip=kind)}
  {share_links(SITE + '/' + path, p['title'], root)}
  {author_card(root)}
  {pager(pubs, i, 'publications')}
</article>"""
        if p.get("abstract"):
            desc = clip(p["abstract"])
        else:
            desc = clip(f"{p['title']} {kind} in {p['journal']}, {month_year(p['date'])}. "
                        f"Authors: {', '.join(p['authors'][:4])}{' et al.' if len(p['authors']) > 4 else ''}")
        doc = page(root=root, path=path, title=f"{p['title']} | {OWNER}", description=desc, body=body,
                   og_type="article", head_extra=citation_extra(p, path), width="article")
        if write(path + "index.html", doc):
            changed.append(path)
        bib_src = ROOT / "data" / "bib" / f"{p['slug']}.bib"
        bib = bib_src.read_text(encoding="utf-8") if bib_src.exists() else make_bib(p)
        write(path + "cite.bib", bib)

    groups = year_groups(pubs, lambda xs: '<ol class="pubs">\n'
                         + "\n".join(pub_item(p, f"{p['slug']}/", show_year=False) for p in xs) + "\n</ol>")
    body = f"""<header class="page-head">
  <h1>Publications</h1>
  <p class="intro">{len(pubs)} peer-reviewed publications, newest first. Also on <a href="https://pubmed.ncbi.nlm.nih.gov/?term=Agargun+BF%5BAuthor%5D&amp;sort=date" target="_blank" rel="noopener">PubMed</a>, <a href="https://scholar.google.com/citations?hl=en&amp;user=MeNxgD4AAAAJ" target="_blank" rel="noopener">Google Scholar</a> and <a href="https://orcid.org/0000-0002-3933-1881" target="_blank" rel="noopener">ORCID</a>.</p>
</header>
{groups}"""
    doc = page(root="../", path="publications/", title=f"Publications | {OWNER}",
               description="Peer-reviewed publications of Besim Fazil Agargun (Besim Fazıl Ağargün), MD, in gastroenterology, hepatology, inflammatory bowel disease and endoscopy.",
               body=body)
    if write("publications/index.html", doc):
        changed.append("publications/")
    return changed


