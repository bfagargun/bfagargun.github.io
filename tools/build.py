# ---------------------------------------------------------------- sitemap and clean-up
def build_sitemap(pubs, talks):
    urls = ["", "experience/", "publications/"] + [f"publications/{p['slug']}/" for p in pubs] \
        + ["events/"] + [f"events/{t['slug']}/" for t in talks]
    body = "\n".join(f"  <url><loc>{SITE}/{u}</loc></url>" for u in urls)
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "\n</urlset>\n")
    return ["sitemap.xml"] if write("sitemap.xml", xml) else []


def remove_stale(folder, slugs):
    removed = []
    base = ROOT / folder
    if not base.exists():
        return removed
    for d in base.iterdir():
        idx = d / "index.html"
        if d.is_dir() and d.name not in slugs and idx.exists() and GENERATED in idx.read_text(encoding="utf-8"):
            shutil.rmtree(d)
            removed.append(f"{folder}/{d.name}/")
    return removed


def main():
    pubs = json.loads((ROOT / "data" / "publications.json").read_text(encoding="utf-8"))
    talks = json.loads((ROOT / "data" / "talks.json").read_text(encoding="utf-8"))
    for kind, items in (("publication", pubs), ("talk", talks)):
        seen = set()
        for x in items:
            if not re.fullmatch(r"[a-z0-9-]+", x["slug"]):
                sys.exit(f"Bad {kind} slug: {x['slug']!r} (use lowercase letters, digits and -)")
            if x["slug"] in seen:
                sys.exit(f"Duplicate {kind} slug: {x['slug']}")
            seen.add(x["slug"])
    pubs.sort(key=lambda p: (p["date"], p["title"]), reverse=True)
    talks.sort(key=lambda t: t["date"], reverse=True)
    changed = build_publications(pubs) + build_talks(talks) + build_blocks(pubs, talks) + build_sitemap(pubs, talks)
    removed = remove_stale("publications", {p["slug"] for p in pubs}) + remove_stale("events", {t["slug"] for t in talks})
    print(f"{len(pubs)} publications, {len(talks)} talks.")
    print("Updated: " + (", ".join(changed) if changed else "nothing (already up to date)"))
    if removed:
        print("Removed: " + ", ".join(removed))


if __name__ == "__main__":
    main()
