# ---------------------------------------------------------------- helpers
def esc(s):
    return html.escape(str(s), quote=True)


def norm(name):
    s = name.replace("ı", "i").replace("İ", "I")
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c)).lower()
    return " ".join(re.sub(r"[^a-z]", " ", s).split())


OWNER_KEYS = {norm(x) for x in (
    "Besim Fazil Agargun", "Besim F Agargun", "Besim Agargun", "BF Agargun", "B F Agargun",
    "Agargun BF", "Agargun B F", "Agargun Besim Fazil", "Agargun Besim F", "Agargun B")}


def is_owner(name):
    return norm(name) in OWNER_KEYS


def icon(name, root):
    return f'<svg class="icon" aria-hidden="true"><use href="{root}assets/icons.svg#{name}"></use></svg>'


def logo(root):
    return f'<svg class="logo" aria-hidden="true" viewBox="0 0 231 346"><use href="{root}assets/icons.svg#gi"></use></svg>'


def ymd(d):
    y, m, day = (int(x) for x in (d.split("-") + ["1", "1"])[:3])
    return y, m, day


def month_year(d):
    y, m, _ = ymd(d)
    return f"{MONTHS[m - 1]} {y}"


def short_month_year(d):
    y, m, _ = ymd(d)
    return f"{MONTHS[m - 1][:3]} {y}"


def short_date(d):
    y, m, day = ymd(d)
    return f"{MONTHS[m - 1][:3]} {day}, {y}"


def date_range(start, end):
    if not end or end == start:
        return short_date(start)
    y1, m1, d1 = ymd(start)
    y2, m2, d2 = ymd(end)
    if (y1, m1) == (y2, m2):
        return f"{MONTHS[m1 - 1][:3]} {d1}-{d2}, {y1}"
    return f"{short_date(start)} - {short_date(end)}"


def day_range(start, end):
    """Like date_range but without the year (used under a year heading)."""
    _, m1, d1 = ymd(start)
    if not end or end == start:
        return f"{MONTHS[m1 - 1][:3]} {d1}"
    _, m2, d2 = ymd(end)
    if m1 == m2:
        return f"{MONTHS[m1 - 1][:3]} {d1}-{d2}"
    return f"{MONTHS[m1 - 1][:3]} {d1} - {MONTHS[m2 - 1][:3]} {d2}"


def inline_md(s):
    s = esc(s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<em>\1</em>", s)
    s = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2" target="_blank" rel="noopener">\1</a>', s)
    return s


def md(text):
    out = []
    for block in re.split(r"\n\s*\n", (text or "").strip()):
        lines = [l.strip() for l in block.strip().split("\n") if l.strip()]
        if not lines:
            continue
        if all(l.startswith(("- ", "* ")) for l in lines):
            out.append("<ul>" + "".join(f"<li>{inline_md(l[2:])}</li>" for l in lines) + "</ul>")
        else:
            out.append(f"<p>{inline_md(' '.join(lines))}</p>")
    return "\n".join(out)


def indent(text, n):
    return "\n".join((" " * n + line) if line else line for line in text.split("\n"))


def clip(text, n=158):
    text = " ".join(str(text).split())
    if len(text) <= n:
        return text
    cut = text[:n].rsplit(" ", 1)[0].rstrip(",;:")
    return cut + "…"


def write(path, text):
    path = ROOT / path
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def jsonld(obj):
    return ('<script type="application/ld+json">\n'
            + json.dumps(obj, ensure_ascii=False, indent=1).replace("</", "<\\/")
            + "\n</script>")


def replace_block(doc, name, content):
    pat = re.compile(r"(<!-- BEGIN:%s -->)(.*?)(<!-- END:%s -->)" % (name, name), re.S)
    if not pat.search(doc):
        sys.exit(f"Marker <!-- BEGIN:{name} --> not found")
    return pat.sub(lambda m: m.group(1) + "\n" + content.rstrip() + "\n" + m.group(3), doc, count=1)


def get_block(doc, name):
    m = re.search(r"<!-- BEGIN:%s -->\n?(.*?)<!-- END:%s -->" % (name, name), doc, re.S)
    if not m:
        sys.exit(f"Marker <!-- BEGIN:{name} --> not found")
    return m.group(1)


def rebase(fragment, prefix):
    """Make relative links in a copied block work from a sub-folder."""
    def fix(m):
        attr, url = m.group(1), m.group(2)
        if re.match(r"^(https?:|mailto:|tel:|data:|#|/|\.\./)", url):
            return m.group(0)
        return f'{attr}="{prefix}{url}"'
    return re.sub(r'\b(href|src|srcset)="([^"]+)"', fix, fragment)


